DEFAULT_FONT = '-apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif'


def js_json(obj):
    """JSON safe to embed in JS/HTML: '<' is escaped so tags can never appear inside the data."""
    return json.dumps(obj, ensure_ascii=False, indent=2).replace("<", "\\u003c").replace(">", "\\u003e").replace("\u2028", "\\u2028")


def build_jsx(content, assets, rng):
    hero = rng.choice([HERO_SPLIT, HERO_CENTER])
    layout = rng.choice(["cards", "list"])
    data = dict(content)
    data.update({"hero": assets["hero"], "logo": assets["logo"], "icons": assets["icons"]})
    jsx = JSX_TEMPLATE.substitute(data=js_json(data), hero=hero, feature_layout=layout)
    return jsx, {"hero": "split" if hero is HERO_SPLIT else "center", "features": layout}


def build_css(assets, rng, mood):
    p = assets["palette"]
    return CSS_TEMPLATE.substitute(
        bg=p["bg"], surface=p["surface"], text=p["text"], muted=p["muted"], primary=p["primary"],
        primary_text=p["primary_text"], accent=p["accent"], radius=rng.choice([6, 12, 20, 28]),
        font=FONTS.get(mood, DEFAULT_FONT),
    )


def build_preview_body(content, assets, layout):
    e = html.escape
    feats = "".join(
        '<article class="card"><span class="icon">%s</span><h3>%s</h3><p>%s</p></article>' % (assets["icons"][i], e(f["title"]), e(f["text"]))
        for i, f in enumerate(content["features"]))
    stats = "".join("<li><strong>%s</strong><span>%s</span></li>" % (e(s["value"]), e(s["label"])) for s in content["stats"])
    about = "".join("<p>%s</p>" % e(p) for p in content["about"])
    btns = ('<div class="btn-row"><a class="btn btn-primary" href="#contact">%s</a>'
            '<a class="btn btn-ghost" href="#features">%s</a></div>' % (e(content["cta_primary"]), e(content["cta_secondary"])))
    text = ('<div class="hero-text"><p class="eyebrow">%s</p><h1>%s</h1><p class="lead">%s</p>%s</div>'
            % (e(" · ".join(content["keywords"])), e(content["hero_heading"]), e(content["tagline"]), btns))
    art = '<div class="hero-art%s">%s</div>' % (" hero-art-bg" if layout["hero"] == "center" else "", assets["hero"])
    hero = '<section class="hero hero-%s">%s</section>' % (layout["hero"], text + art if layout["hero"] == "split" else art + text)
    return (
        '<header class="site-header"><a class="brand" href="#top"><span class="logo">%s</span><span>%s</span></a>'
        '<nav><a href="#about">About</a><a href="#features">%s</a><a href="#contact">Contact</a></nav></header>\n'
        '<main>%s\n<section id="about" class="section about"><h2>%s</h2>%s<ul class="stats">%s</ul></section>\n'
        '<section id="features" class="section features %s"><h2>%s</h2><div class="grid">%s</div></section>\n'
        '<section id="contact" class="section cta"><h2>%s</h2><p>%s</p><a class="btn btn-primary" href="#top">%s</a></section></main>\n'
        '<footer class="site-footer">%s</footer>'
        % (assets["logo"], e(content["brand"]), e(content["features_title"]), hero, e(content["about_title"]), about, stats,
           layout["features"], e(content["features_title"]), feats, e(content["cta_title"]), e(content["cta_text"]),
           e(content["cta_primary"]), e(content["footer"])))


def validate_jsx(jsx):
    """Custom JSX sanity check: DATA parses as JSON, brackets balance, tags nest correctly, required parts exist."""
    m = re.search(r"const DATA = (\{.*?\n\});\n", jsx, re.S)
    if not m:
        raise ValueError("DATA block not found")
    json.loads(m.group(1))
    code = jsx[m.end():]
    code = re.sub(r"//[^\n]*", "", code)
    code = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)
    stack = []
    pairs = {")": "(", "]": "[", "}": "{"}
    for ch in code:
        if ch in "([{":
            stack.append(ch)
        elif ch in pairs:
            if not stack or stack.pop() != pairs[ch]:
                raise ValueError("unbalanced bracket " + ch)
    if stack:
        raise ValueError("unclosed bracket(s): " + "".join(stack))
    tags = []
    for t in re.finditer(r"<(/?)([A-Za-z][\w.]*)([^<>]*?)(/?)>", code):
        close, name, attrs, selfclose = t.groups()
        if selfclose or name in ("br", "img", "hr", "input", "meta", "link"):
            continue
        if close:
            if not tags or tags.pop() != name:
                raise ValueError("mismatched closing tag </%s>" % name)
        else:
            tags.append(name)
    if tags:
        raise ValueError("unclosed tag(s): %s" % tags)
    for need in ("function App", "ReactDOM.createRoot", "function Hero", "function Features"):
        if need not in code:
            raise ValueError("missing " + need)
    return True


def generate_site(content, assets, out_dir, seed=None):
    rng = random.Random(None if seed is None else seed + 2)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    jsx, layout = build_jsx(content, assets, rng)
    validate_jsx(jsx)
    from .asset_engine import data_uri
    fav = data_uri(assets["logo"])
    meta = {"title": html.escape(content["brand"] + " | " + content["hero_heading"]), "description": html.escape(content["tagline"], quote=True), "favicon": fav}
    files = {
        "App.jsx": jsx,
        "styles.css": build_css(assets, rng, content["mood"]),
        "index.html": INDEX_TEMPLATE.substitute(**meta),
        "preview.html": PREVIEW_TEMPLATE.substitute(body=build_preview_body(content, assets, layout), **meta),
    }
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
    return {"dir": str(out), "files": sorted(files), "layout": layout}
