import { useEffect, useMemo, useState } from 'react';
import { createUpiClient, canOpenUpiApp } from 'pure-upi/client';

export default function UpiCheckout({ plan, baseUrl = '/api/upi', onPaid }) {
  const upi = useMemo(() => createUpiClient({ baseUrl }), [baseUrl]);
  const [data, setData] = useState(null); // { order, link, qrSvg }
  const [utr, setUtr] = useState('');
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const status = data?.order.status;

  // While the admin verifies, poll every 5s
  useEffect(() => {
    if (status !== 'submitted') return undefined;
    const t = setInterval(async () => {
      const { order } = await upi.getOrder(data.order.id);
      setData((d) => ({ ...d, order }));
      if (order.status === 'approved') onPaid?.(order);
    }, 5000);
    return () => clearInterval(t);
  }, [status, data?.order.id, upi, onPaid]);

  const run = (fn) => async () => {
    setBusy(true);
    setError('');
    try { await fn(); } catch (e) { setError(e.message); } finally { setBusy(false); }
  };
  const start = run(async () => setData(await upi.createOrder(plan)));
  const submit = run(async () => {
    const order = await upi.submitUtr(data.order.id, utr);
    setData((d) => ({ ...d, order }));
  });

  if (!data) return <button disabled={busy} onClick={start}>Buy Premium</button>;
  if (status === 'approved') return <p>Payment verified. Premium is active!</p>;
  if (status === 'rejected') {
    return (
      <div>
        <p>Payment rejected{data.order.reason ? `: ${data.order.reason}` : ''}.</p>
        <button onClick={() => setData(null)}>Try again</button>
      </div>
    );
  }
  if (status === 'submitted') return <p>Payment submitted (UTR {data.order.utr}). Verifying…</p>;

  return (
    <div>
      <h3>Pay exactly ₹{data.order.amount}</h3>
      {/* qrSvg is generated by pure-upi on your own server (no user input inside), so it is safe to inject */}
      <div style={{ width: 240, background: '#fff' }} dangerouslySetInnerHTML={{ __html: data.qrSvg }} />
      {canOpenUpiApp() && <a href={data.link}>Open UPI app</a>}
      <p>After paying, enter the 12-digit UTR / UPI Ref No. from your UPI app:</p>
      <input value={utr} onChange={(e) => setUtr(e.target.value)} inputMode="numeric" placeholder="412345678901" />
      <button disabled={busy} onClick={submit}>I have paid</button>
      {error && <p style={{ color: 'crimson' }}>{error}</p>}
    </div>
  );
}
